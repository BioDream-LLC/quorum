#pragma once

// The binding layer: physical signals to asserted propositions.
//
// This is the most dangerous component in the product, and it is dangerous for a subtle reason. Everything above it
// -- the framework, the arbiter, the witness -- is auditable: every inference is an edge, every verdict cites the
// arguments that produced it. The binding layer is where a number becomes a proposition, and a threshold buried in
// C is a diagnostic decision that no witness will ever mention. Move one constant and the machine reaches a
// different conclusion with an explanation that never refers to the change.
//
// So this component is deliberately kept incapable of judgement. It answers exactly one question per observation --
// "did the plant assert this?" -- and every constant it uses comes from the casebook source, where it is reviewed,
// versioned and carried in the provenance block. There is no tuning parameter here that an engineer cannot read in
// the .cb file.
//
// THE CENTRAL REQUIREMENT: a sensor that cannot be believed must not look like a sensor reporting nothing.
//
// The witness work already established this: "no sensor asserted vibration" and "there is no vibration" are
// different statements, and a dead sensor produces the first while reading exactly like the second. Under closed
// world an absent observation is Out, so a dead channel silently becomes positive evidence of health. That is the
// CAPECO failure mode in one sentence -- a frozen level transmitter read as "the tank is not full".
//
// The mechanism: every channel owns an `unavailable` observation. When the channel cannot be believed, this layer
// asserts that observation and suppresses ALL of the channel's threshold observations. The casebook then reasons
// about the sensor failure explicitly, in arguments, where the witness can cite it.
//
// ARITHMETIC. No floating point anywhere on device. Authors write `7.1 mm/s` in the casebook and the compiler
// converts to scaled integers at build time, so the device performs integer comparisons only. Host-side floating
// point at compile time, integer comparisons at run time.
//
// Freestanding: no heap, no exceptions, no recursion, no static initialisation order, <cstdint>/<cstddef> only.

#include <cstddef>
#include <cstdint>

namespace quorum::binding {

/// Values are carried as milli-units of whatever the channel declares: 7.1 mm/s is 7100. One uniform scale keeps
/// the device arithmetic trivial; the unit string is documentation carried through for the witness.
constexpr std::int32_t kScale = 1000;

enum class Status : std::uint8_t {
    Ok = 0,
    NotConfigured,
    BadChannel,
    CapacityExceeded,
    BadSpec,
};

/// Which side of the threshold asserts the observation.
enum class Sense : std::uint8_t {
    Above = 0,  ///< assert when the value rises to `on`, release when it falls to `off`
    Below = 1,  ///< assert when the value falls to `on`, release when it rises to `off`
};

/// A physical signal. Generated by cbc from a `channel` declaration; never hand-written.
struct ChannelSpec {
    std::int32_t valid_lo = 0;  ///< milli-units; a sample outside [lo, hi] is instrument nonsense, not data
    std::int32_t valid_hi = 0;
    /// How long a sample stays believable. Exceeded means unavailable. There is no "0 means never expire" escape
    /// hatch: a channel with no freshness requirement cannot be distinguished from a dead one, and offering the
    /// option would make the dangerous choice available.
    std::uint32_t stale_after_ms = 0;
    /// How long a value may sit unchanged before the channel is reported as flatlined. 0 disables the check.
    ///
    /// This is NOT staleness. A stale channel has stopped delivering samples; a flatlined channel delivers fresh
    /// samples that never move, which is what a failed 4-20 mA transmitter or a latched ADC actually does, and is
    /// what nobody at CAPECO detected.
    std::uint32_t flatline_after_ms = 0;
    /// How much movement counts as alive, in milli-units. Guards against dither being mistaken for signal.
    std::int32_t flatline_epsilon = 0;
    std::int32_t unavailable_obs = -1;  ///< observation asserted when this channel cannot be believed
    std::int32_t flatline_obs = -1;     ///< observation asserted when the value has stopped moving, or -1
};

/// One threshold on one channel. The hysteresis pair is required, not optional -- a bare threshold chatters, and a
/// chattering observation makes the framework oscillate between verdicts, which is the alarm-flooding failure this
/// product exists to avoid.
struct ThresholdSpec {
    std::int32_t channel = 0;
    std::int32_t observation = -1;
    Sense sense = Sense::Above;
    std::int32_t on = 0;   ///< milli-units; crossing this asserts
    std::int32_t off = 0;  ///< milli-units; crossing back past this releases
    /// How long the value must stay past `on` before the observation asserts. 0 asserts at once, as before.
    ///
    /// "Bearing temperature above 90 for 5 s" is how alarm philosophies are actually written (an on-delay, ISA-18.2),
    /// and it is what separates a real condition from a spike. It lives here, in the binding, and not in the
    /// framework, deliberately: the framework stays a function of the present presence mask, so exhaustive and
    /// symbolic validation still cover every state exactly. Time decides only WHEN a bit is set, never what a set
    /// bit means.
    ///
    /// The hold restarts whenever a sample falls back below `on` before it matures. Release is not delayed: once
    /// asserted, the observation releases at `off` exactly as without a hold, because delaying the release of an
    /// alarm condition is the dangerous direction.
    std::uint32_t hold_ms = 0;
};

/// Why a channel is not believable, for the witness. Ordered by how much it tells you.
enum class Health : std::uint8_t {
    Good = 0,
    NeverSampled,  ///< the device has booted but has not yet read this channel
    Faulted,       ///< the caller reported the read itself as failed
    OutOfRange,    ///< the last sample is outside the declared valid range
    Stale,         ///< no fresh sample within stale_after_ms
};

[[nodiscard]] constexpr const char* health_name(Health h) noexcept {
    switch (h) {
        case Health::Good: return "good";
        case Health::NeverSampled: return "never sampled";
        case Health::Faulted: return "read faulted";
        case Health::OutOfRange: return "out of range";
        case Health::Stale: return "stale";
    }
    return "unknown";
}

/// Turns samples into a presence mask.
///
/// Fixed capacity, no allocation, safe to place in static storage. `MaxChannels` and `MaxThresholds` come from the
/// generated header so a casebook's binding is sized exactly.
template <std::int32_t MaxChannels, std::int32_t MaxThresholds>
class Binding {
    static_assert(MaxChannels > 0, "a binding needs at least one channel");
    static_assert(MaxThresholds > 0, "a binding needs at least one threshold");

    static constexpr std::size_t kChannelSlots = static_cast<std::size_t>(MaxChannels);
    static constexpr std::size_t kThresholdSlots = static_cast<std::size_t>(MaxThresholds);

    [[nodiscard]] static constexpr std::size_t ix(std::int32_t i) noexcept {
        return static_cast<std::size_t>(i);
    }

public:
    constexpr Binding() noexcept = default;

    /// Install the generated tables. The spec arrays must outlive this object; they are `constexpr` in the
    /// generated header, so in practice they live in flash and are never copied to RAM.
    [[nodiscard]] Status configure(const ChannelSpec* channels,
                                   std::int32_t channel_count,
                                   const ThresholdSpec* thresholds,
                                   std::int32_t threshold_count) noexcept {
        if (channels == nullptr || thresholds == nullptr) { return Status::BadSpec; }
        if (channel_count < 0 || threshold_count < 0) { return Status::BadSpec; }
        if (channel_count > MaxChannels || threshold_count > MaxThresholds) {
            return Status::CapacityExceeded;
        }

        for (std::int32_t c = 0; c < channel_count; ++c) {
            const ChannelSpec& s = channels[ix(c)];
            if (s.valid_hi < s.valid_lo) { return Status::BadSpec; }
            // A channel with no freshness requirement can never be reported dead, which defeats the entire point
            // of this layer. Refuse it at configure time rather than discover it in the field.
            if (s.stale_after_ms == 0) { return Status::BadSpec; }
            if (s.unavailable_obs < 0) { return Status::BadSpec; }
        }
        for (std::int32_t t = 0; t < threshold_count; ++t) {
            const ThresholdSpec& s = thresholds[ix(t)];
            if (s.channel < 0 || s.channel >= channel_count) { return Status::BadSpec; }
            if (s.observation < 0) { return Status::BadSpec; }
            // Hysteresis must be a genuine deadband in the right direction, or it is not hysteresis.
            if (s.sense == Sense::Above && s.off > s.on) { return Status::BadSpec; }
            if (s.sense == Sense::Below && s.off < s.on) { return Status::BadSpec; }
        }

        channels_ = channels;
        thresholds_ = thresholds;
        channel_count_ = channel_count;
        threshold_count_ = threshold_count;

        // Boot state. Every channel is NeverSampled, so the very first mask reports every channel unavailable and
        // asserts no threshold at all. A binding layer that gives a clean bill of health before reading a single
        // sensor is the worst possible failure, so it is the default that has to be got right.
        for (std::int32_t c = 0; c < channel_count; ++c) {
            seen_[ix(c)] = false;
            faulted_[ix(c)] = false;
            value_[ix(c)] = 0;
            updated_ms_[ix(c)] = 0;
            moved_ms_[ix(c)] = 0;
            anchor_[ix(c)] = 0;
        }
        for (std::int32_t t = 0; t < threshold_count; ++t) {
            latched_[ix(t)] = false;
            pending_[ix(t)] = false;
            pending_since_ms_[ix(t)] = 0;
        }
        return Status::Ok;
    }

    /// Record a good sample, in milli-units.
    [[nodiscard]] Status sample(std::int32_t channel, std::int32_t milli, std::uint32_t now_ms) noexcept {
        if (channels_ == nullptr) { return Status::NotConfigured; }
        if (channel < 0 || channel >= channel_count_) { return Status::BadChannel; }

        const ChannelSpec& spec = channels_[ix(channel)];
        const bool in_range = milli >= spec.valid_lo && milli <= spec.valid_hi;

        // Flatline tracking runs off the last sample that actually MOVED, not the last sample received. Tracking
        // the latter would mean a transmitter repeating one value forever looks continuously fresh -- exactly the
        // condition this is here to catch.
        if (!seen_[ix(channel)] || !in_range) {
            anchor_[ix(channel)] = milli;
            moved_ms_[ix(channel)] = now_ms;
        } else {
            const std::int32_t delta = milli - anchor_[ix(channel)];
            const std::int32_t magnitude = delta < 0 ? -delta : delta;
            if (magnitude > spec.flatline_epsilon) {
                anchor_[ix(channel)] = milli;
                moved_ms_[ix(channel)] = now_ms;
            }
        }

        value_[ix(channel)] = milli;
        updated_ms_[ix(channel)] = now_ms;
        seen_[ix(channel)] = true;
        faulted_[ix(channel)] = false;

        // An out-of-range sample is instrument nonsense. It updates freshness -- the channel is talking -- but it
        // must never move a latch, because latching on garbage is how a spurious shutdown happens.
        if (in_range) { relatch(channel, milli, now_ms); }
        return Status::Ok;
    }

    /// Record that the read itself failed: no response on the bus, a 4-20 mA loop reading 2 mA, a checksum error.
    /// Distinct from an out-of-range value, and the witness reports it differently.
    [[nodiscard]] Status fault(std::int32_t channel, std::uint32_t now_ms) noexcept {
        if (channels_ == nullptr) { return Status::NotConfigured; }
        if (channel < 0 || channel >= channel_count_) { return Status::BadChannel; }
        faulted_[ix(channel)] = true;
        updated_ms_[ix(channel)] = now_ms;
        return Status::Ok;
    }

    /// Why this channel is or is not believable, evaluated at `now_ms`.
    [[nodiscard]] Health health(std::int32_t channel, std::uint32_t now_ms) const noexcept {
        if (channels_ == nullptr || channel < 0 || channel >= channel_count_) { return Health::NeverSampled; }
        if (!seen_[ix(channel)]) { return Health::NeverSampled; }
        if (faulted_[ix(channel)]) { return Health::Faulted; }

        const ChannelSpec& spec = channels_[ix(channel)];
        const std::int32_t v = value_[ix(channel)];
        if (v < spec.valid_lo || v > spec.valid_hi) { return Health::OutOfRange; }

        // Unsigned subtraction, deliberately. A device that has been running 50 days rolls `now_ms` through zero,
        // and computing the age as a signed difference would make every channel look freshly sampled at exactly the
        // moment the plant has been trusted longest. Modular arithmetic is correct for any interval below 2^32 ms.
        if (static_cast<std::uint32_t>(now_ms - updated_ms_[ix(channel)]) >= spec.stale_after_ms) {
            return Health::Stale;
        }
        return Health::Good;
    }

    /// Has this channel stopped moving? Only meaningful when `health` is Good.
    [[nodiscard]] bool flatlined(std::int32_t channel, std::uint32_t now_ms) const noexcept {
        if (channels_ == nullptr || channel < 0 || channel >= channel_count_) { return false; }
        const ChannelSpec& spec = channels_[ix(channel)];
        if (spec.flatline_after_ms == 0 || spec.flatline_obs < 0) { return false; }
        if (health(channel, now_ms) != Health::Good) { return false; }
        return static_cast<std::uint32_t>(now_ms - moved_ms_[ix(channel)]) >= spec.flatline_after_ms;
    }

    /// The presence mask to hand to the casebook.
    ///
    /// Two rules, and they are the whole contract:
    ///   1. an unbelievable channel asserts its `unavailable` observation and NONE of its thresholds;
    ///   2. a believable channel asserts its latched thresholds and not `unavailable`.
    ///
    /// The mask therefore never says "quiet" when it means "blind".
    [[nodiscard]] std::uint32_t mask(std::uint32_t now_ms) const noexcept {
        std::uint32_t m = 0;
        if (channels_ == nullptr) { return m; }

        for (std::int32_t c = 0; c < channel_count_; ++c) {
            const ChannelSpec& spec = channels_[ix(c)];
            if (health(c, now_ms) != Health::Good) {
                m |= obs_bit(spec.unavailable_obs);
                continue;
            }
            if (flatlined(c, now_ms)) { m |= obs_bit(spec.flatline_obs); }
        }

        for (std::int32_t t = 0; t < threshold_count_; ++t) {
            const ThresholdSpec& spec = thresholds_[ix(t)];
            if (!asserted(t, now_ms)) { continue; }
            if (health(spec.channel, now_ms) != Health::Good) { continue; }
            m |= obs_bit(spec.observation);
        }
        return m;
    }

    /// Is threshold `t` asserting at `now_ms`? Latched, or past `on` for at least its hold time.
    ///
    /// Evaluated at mask time as well as at sample time, so a hold matures on schedule even if no further sample
    /// arrives -- a channel that then goes quiet for too long is caught by staleness, not by this.
    [[nodiscard]] bool asserted(std::int32_t t, std::uint32_t now_ms) const noexcept {
        if (t < 0 || t >= threshold_count_) { return false; }
        if (latched_[ix(t)]) { return true; }
        return pending_[ix(t)] &&
               static_cast<std::uint32_t>(now_ms - pending_since_ms_[ix(t)]) >= thresholds_[ix(t)].hold_ms;
    }

    [[nodiscard]] constexpr std::int32_t channel_count() const noexcept { return channel_count_; }
    [[nodiscard]] constexpr std::int32_t threshold_count() const noexcept { return threshold_count_; }

    /// The last accepted sample, in milli-units. For the witness, so a verdict can quote the number a human saw on
    /// the gauge rather than only the proposition it became.
    [[nodiscard]] std::int32_t value(std::int32_t channel) const noexcept {
        if (channel < 0 || channel >= channel_count_) { return 0; }
        return value_[ix(channel)];
    }

private:
    /// The presence-mask bit for an observation index.
    ///
    /// NAMED `obs_bit` AND NOT `bit`, WHICH IT WAS UNTIL A REAL BOARD REJECTED IT.
    ///
    /// The Arduino core's api/Common.h contains `#define bit(b) (1UL << (b))`, guarded only by `#ifndef bit` -- which
    /// a C++ function does not satisfy. The preprocessor therefore rewrote this function's own definition into
    /// `std::uint32_t (1UL << (observation))` and reported the error against Arduino's header, not this one.
    ///
    /// Second collision of this kind found by the first real vendor toolchain the code ever met; the other was an
    /// enumerator named `SysTick`, which CMSIS also #defines. Neither was caught by the portability gate, because
    /// that gate compiles against a stub Arduino.h containing none of the vendor macros.
    [[nodiscard]] static constexpr std::uint32_t obs_bit(std::int32_t observation) noexcept {
        if (observation < 0 || observation >= 32) { return 0U; }
        return 1U << static_cast<std::uint32_t>(observation);
    }

    void relatch(std::int32_t channel, std::int32_t milli, std::uint32_t now_ms) noexcept {
        for (std::int32_t t = 0; t < threshold_count_; ++t) {
            const ThresholdSpec& spec = thresholds_[ix(t)];
            if (spec.channel != channel) { continue; }
            const bool past_on = spec.sense == Sense::Above ? milli >= spec.on : milli <= spec.on;
            const bool past_off = spec.sense == Sense::Above ? milli <= spec.off : milli >= spec.off;
            // A matured hold becomes a latch before this sample is judged, so a sample in the deadband after the
            // hold has elapsed keeps the observation asserted, as hysteresis requires.
            if (asserted(t, now_ms)) { latched_[ix(t)] = true; }
            if (past_on) {
                if (!latched_[ix(t)] && !pending_[ix(t)]) {
                    pending_[ix(t)] = true;
                    pending_since_ms_[ix(t)] = now_ms;
                }
                if (spec.hold_ms == 0U) { latched_[ix(t)] = true; }
            } else {
                // Fell back before maturing: the condition was not sustained, so the hold starts again next time.
                pending_[ix(t)] = false;
                if (past_off) { latched_[ix(t)] = false; }
            }
            if (latched_[ix(t)]) { pending_[ix(t)] = false; }
            // Between `on` and `off` a latch deliberately holds its previous state. That band is the deadband.
        }
    }

    const ChannelSpec* channels_ = nullptr;
    const ThresholdSpec* thresholds_ = nullptr;
    std::int32_t channel_count_ = 0;
    std::int32_t threshold_count_ = 0;

    std::int32_t value_[kChannelSlots]{};
    std::uint32_t updated_ms_[kChannelSlots]{};
    std::int32_t anchor_[kChannelSlots]{};     ///< last value considered to be movement
    std::uint32_t moved_ms_[kChannelSlots]{};  ///< when that movement was seen
    bool seen_[kChannelSlots]{};
    bool faulted_[kChannelSlots]{};

    bool latched_[kThresholdSlots]{};
    bool pending_[kThresholdSlots]{};               ///< past `on`, waiting out the hold
    std::uint32_t pending_since_ms_[kThresholdSlots]{};
};

}  // namespace quorum::binding
